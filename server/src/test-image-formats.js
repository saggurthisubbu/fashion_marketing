async function testUploads() {
  console.log('🧪 Testing image upload formats: JPG, JPEG, PNG, WEBP...');
  let passed = 0;

  for (const fmt of formats) {
    const filename = `test-format-${Date.now()}.${fmt.ext}`;
    const blob = new Blob([fmt.buffer], { type: fmt.mime });
    const formData = new FormData();
    formData.append('image', blob, filename);

    try {
      const res = await fetch('http://localhost:5000/api/upload', {
        method: 'POST',
        body: formData
      });

      const data = await res.json();
      if (res.status === 200 && data.success) {
        console.log(`✅ [${fmt.ext.toUpperCase()}]: Uploaded successfully -> ${data.imageUrl}`);
        
        // Verify Express serves it
        const getExpress = await fetch('http://localhost:5000' + data.imageUrl);
        // Verify Vite serves it
        const getVite = await fetch('http://localhost:5173' + data.imageUrl);

        if (getExpress.status === 200 && getVite.status === 200) {
          console.log(`   Express: 200 ${getExpress.headers.get('content-type')} | Vite: 200 ${getVite.headers.get('content-type')}`);
          passed++;
        } else {
          console.error(`   ❌ Failed to serve image! Express: ${getExpress.status}, Vite: ${getVite.status}`);
        }
      } else {
        console.error(`❌ [${fmt.ext.toUpperCase()}]: Upload failed:`, data);
      }
    } catch (err) {
      console.error(`❌ [${fmt.ext.toUpperCase()}]: Error:`, err.message);
    }
  }

  console.log(`\n🎉 Test Complete: ${passed}/${formats.length} image formats verified successfully.`);
  process.exit(passed === formats.length ? 0 : 1);
}

testUploads();
